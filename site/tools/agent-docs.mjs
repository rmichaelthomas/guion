import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { SITE_ROOT, allhereRepo } from './lib/paths.mjs';

const SECTION_START = /<(?:section|footer) class="section[^"]*"[^>]*\bid="([^"]+)"/g;
const BAR = 'bar';

/** Every instrument id carried by a `data-ahi` attribute on the built page, with where and how it appears. */
function instrumentsOnPage(html) {
  const starts = [...html.matchAll(SECTION_START)].map((match) => ({ id: match[1], at: match.index }));
  const found = new Map();
  for (const match of html.matchAll(/data-ahi="(ahi\.[^"]+)"/g)) {
    const section = [...starts].reverse().find((start) => start.at < match.index)?.id ?? BAR;
    const tagStart = html.lastIndexOf('<', match.index);
    const tag = html.slice(tagStart, html.indexOf('>', match.index) + 1);
    const vendored = tag.includes('data-ahi-renderer=');
    const slot = /\bid="slot-([^"]+)"/.exec(tag)?.[1];
    const key = `${section}|${match[1]}|${vendored}|${slot ?? ''}`;
    if (!found.has(key)) found.set(key, { section, id: match[1], vendored, slot });
  }
  const order = [BAR, ...starts.map((start) => start.id)];
  return [...found.values()].sort((a, b) => order.indexOf(a.section) - order.indexOf(b.section) || a.id.localeCompare(b.id) || String(a.slot).localeCompare(String(b.slot)));
}

export function familiesIn(html) {
  return new Set(instrumentsOnPage(html).map((entry) => entry.id.split('.')[1]));
}

const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));

export function renderInstrumentMap({ html, allhere }) {
  const catalog = readJson(path.join(allhere, 'instruments', 'registry', 'catalog.json'));
  const behaviors = readJson(path.join(allhere, 'instruments', 'registry', 'behaviors.json'));
  const nameOf = new Map(catalog.instruments.map((item) => [item.id, item]));
  const behaviorOf = new Map(behaviors.instruments.map((item) => [item.id, item]));
  const rows = instrumentsOnPage(html);
  const families = new Set(rows.map((row) => row.id.split('.')[1]));
  const lines = [
    '# Instrument map',
    '',
    'Generated by `node site/tools/agent-docs.mjs` from `site/public/index.html` and the AllHereHTML registry. Do not edit by hand.',
    '',
    `Instruments in use: ${new Set(rows.map((row) => row.id)).size} of ${catalog.instruments.length} · families: ${families.size} of ${catalog.families.length}.`,
    '',
    '**How** is one of:',
    '- *vendored* — rendered by AllHere\'s own visitor renderer and slotted in from `site/vendor/allhere/fragments/` (slot id shown).',
    '- *authored* — hand-built markup that follows the instrument\'s registry contract (semantic element, interaction, fallback) and carries its `data-ahi` id. Used where the registry\'s four text fields (heading, body, caption, note) cannot hold the real content.',
    '',
    '| Section | Instrument | Family | Renderer | How |',
    '|---|---|---|---|---|',
  ];
  for (const row of rows) {
    const item = nameOf.get(row.id);
    const behavior = behaviorOf.get(row.id);
    lines.push(`| ${row.section} | ${item?.name ?? row.id} (\`${row.id}\`) | ${row.id.split('.')[1]} | ${behavior?.renderer ?? '?'} | ${row.vendored ? `vendored, slot \`${row.slot}\`` : 'authored'} |`);
  }
  lines.push('', 'To find another piece: read `instruments/registry/catalog.json` (id, name, family) and `behaviors.json` (renderer, semantic element, interaction, fallback) in the AllHereHTML checkout. See [allhere-toolkit.md](allhere-toolkit.md).', '');
  return lines.join('\n');
}

export function renderContentSources({ claims }) {
  const lines = [
    '# Content sources',
    '',
    'Generated by `node site/tools/agent-docs.mjs` from `site/src/claims.json`. Do not edit by hand.',
    '',
    'Every figure on the page lives in a claim in `site/src/claims.json`. `node --test \'site/tests/*.test.mjs\'` fails if a figure, a stated condition, or any multi-digit number in a claim\'s prose is not found in the files listed here. Paths are relative to the repository root.',
    '',
    '| Claim | Group | Source files checked | Files published as evidence |',
    '|---|---|---|---|',
  ];
  for (const claim of claims) {
    lines.push(`| \`${claim.id}\` | ${claim.group ?? ''} | ${claim.sources.map((source) => `\`${source.path}\``).join('<br>')} | ${claim.evidence.map((file) => `\`${file}\``).join('<br>')} |`);
  }
  lines.push(
    '',
    '## When a number changes',
    '',
    '1. Update the report in the repository first. The report is the source of truth, not this page.',
    '2. Edit the claim in `site/src/claims.json` so its `plain`, `dev.rows`, `figures` and `sources[].needles` match the report\'s new wording exactly.',
    '3. Run `node --test \'site/tests/*.test.mjs\'`. A figure that is not in its source, or a condition the report no longer states, fails here.',
    '4. Run `node site/tools/agent-docs.mjs`, `node site/tools/build.mjs` and `node site/tools/check-site.mjs site/public`. The evidence page re-hashes the copied files.',
    '',
  );
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = readFileSync(path.join(SITE_ROOT, 'public', 'index.html'), 'utf8');
  const claims = readJson(path.join(SITE_ROOT, 'src', 'claims.json'));
  writeFileSync(path.join(SITE_ROOT, 'agents', 'instrument-map.md'), renderInstrumentMap({ html, allhere: allhereRepo() }));
  writeFileSync(path.join(SITE_ROOT, 'agents', 'content-sources.md'), renderContentSources({ claims }));
  console.log('Wrote site/agents/instrument-map.md and site/agents/content-sources.md');
}

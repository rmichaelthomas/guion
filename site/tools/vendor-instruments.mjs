import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { SITE_ROOT, allhereRepo } from './lib/paths.mjs';

const MOTION_TAIL = '@media(prefers-reduced-motion:reduce)';
const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const coreCache = new Map();

async function loadCore(allhere) {
  if (!coreCache.has(allhere)) {
    const core = await import(pathToFileURL(path.join(allhere, 'workshop', 'core.mjs')).href);
    const catalog = JSON.parse(await readFile(path.join(allhere, 'instruments', 'registry', 'catalog.json'), 'utf8'));
    coreCache.set(allhere, { core, catalog });
  }
  return coreCache.get(allhere);
}

function renderDocument({ core, catalog }, nodes) {
  const document = core.createDocument({ id: 'vendor', title: 'vendor', theme: 'paper' });
  document.nodes.push(...nodes);
  return core.renderVisitorDocument(document, catalog, { title: 'vendor' });
}

/** The CSS AllHere adds for one family: its style block minus the page-level baseline and the motion tail. */
function familyCss(ctx, node) {
  const head = (html) => {
    const style = html.match(/<style>([\s\S]*?)<\/style>/)[1];
    return style.slice(0, style.lastIndexOf(MOTION_TAIL));
  };
  const baseline = head(renderDocument(ctx, []));
  const withNode = head(renderDocument(ctx, [node]));
  if (!withNode.startsWith(baseline)) throw new Error(`Unexpected AllHere style layout for ${node.instrumentId}`);
  return withNode.slice(baseline.length);
}

/**
 * Render one instrument through AllHere's own visitor renderer and return a fragment free of
 * AllHere's per-piece contract note and anchor, plus the family CSS that fragment needs.
 */
export async function renderSlot(allhere, slot) {
  const ctx = await loadCore(allhere);
  const nodeId = `slot-${slot.id}`;
  const node = ctx.core.createInstrument(ctx.catalog, slot.instrumentId, slot.content ?? {}, nodeId);
  const page = renderDocument(ctx, [node]);
  const start = page.indexOf('<div class="composition">') + '<div class="composition">'.length;
  const end = page.lastIndexOf('</div>', page.indexOf('<footer class="page-foot"'));
  const noteId = `${nodeId}-instrument-note`;
  const fragment = page
    .slice(start, end)
    .replace(new RegExp(`<details id="${noteId}"[\\s\\S]*?</details>`), '')
    .replace(new RegExp(`<p class="instrument-action"><a href="#${noteId}">[\\s\\S]*?</a></p>`), '')
    .trim();
  return { html: `<div class="ahi">${fragment}</div>`, css: familyCss(ctx, node), family: node.family };
}

export async function vendor({ allhere, slots, outDir }) {
  const renderSlots = slots.filter((slot) => slot.mode === 'render');
  const fragmentsDir = path.join(outDir, 'fragments');
  await rm(fragmentsDir, { recursive: true, force: true });
  await mkdir(fragmentsDir, { recursive: true });

  const files = [];
  const write = async (relative, text) => {
    await writeFile(path.join(outDir, relative), text);
    files.push({ path: relative, sha256: sha256(text) });
  };

  const cssByFamily = new Map();
  for (const slot of renderSlots) {
    const { html, css, family } = await renderSlot(allhere, slot);
    await write(`fragments/${slot.id}.html`, `${html}\n`);
    cssByFamily.set(family, css);
  }
  for (const [family, css] of [...cssByFamily].sort(([a], [b]) => a.localeCompare(b))) {
    await write(`family-${family}.css`, `.ahi{${css}}\n`);
  }

  const allhereCommit = execFileSync('git', ['-C', allhere, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const catalogHash = sha256(await readFile(path.join(allhere, 'instruments', 'registry', 'catalog.json')));
  files.sort((a, b) => a.path.localeCompare(b.path));
  const provenance = [
    '# Vendored AllHereHTML instruments',
    '',
    'Generated by `node site/tools/vendor-instruments.mjs`. Do not edit by hand.',
    '',
    `- AllHereHTML commit: ${allhereCommit}`,
    `- Registry catalog.json sha256: ${catalogHash}`,
    '- Renderer: workshop/core.mjs `createInstrument` + `renderVisitorDocument`; the per-piece contract note and anchor are removed, family CSS is nested under `.ahi`.',
    '',
    '| file | sha256 |',
    '|---|---|',
    ...files.map((file) => `| ${file.path} | ${file.sha256} |`),
    '',
  ].join('\n');
  await writeFile(path.join(outDir, 'PROVENANCE.md'), provenance);
  return { allhereCommit, files };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { slots } = JSON.parse(await readFile(path.join(SITE_ROOT, 'src', 'instruments.json'), 'utf8'));
  const result = await vendor({ allhere: allhereRepo(), slots, outDir: path.join(SITE_ROOT, 'vendor', 'allhere') });
  console.log(`Vendored ${result.files.length} files from AllHereHTML ${result.allhereCommit.slice(0, 7)}`);
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mode {
    Text,
    Lt,
    EndOpen,
    Bang,
    Comment,
    Decl,
    TagName,
    EndTag,
    InTag,
    AttrName,
    AfterAttrName,
    BeforeValue,
    ValueDq,
    ValueSq,
    ValueUnquoted,
    Raw,
}

#[derive(Clone, Debug)]
struct Html {
    mode: Mode,
    tag: String,
    attr: String,
    raw: String,
    dashes: u8,
    tail: String,
}

impl PartialEq for Html {
    fn eq(&self, other: &Self) -> bool {
        if self.mode != other.mode {
            return false;
        }
        match self.mode {
            Mode::Text
            | Mode::Lt
            | Mode::EndOpen
            | Mode::Bang
            | Mode::Comment
            | Mode::Decl
            | Mode::EndTag => true,
            Mode::TagName | Mode::InTag => self.tag == other.tag,
            Mode::AttrName
            | Mode::AfterAttrName
            | Mode::BeforeValue
            | Mode::ValueDq
            | Mode::ValueSq
            | Mode::ValueUnquoted => self.tag == other.tag && self.attr == other.attr,
            Mode::Raw => self.raw == other.raw,
        }
    }
}

impl Html {
    fn new() -> Self {
        Self {
            mode: Mode::Text,
            tag: String::new(),
            attr: String::new(),
            raw: String::new(),
            dashes: 0,
            tail: String::new(),
        }
    }

    fn finish_tag(&mut self) {
        if self.tag == "script" || self.tag == "style" {
            self.mode = Mode::Raw;
            self.raw = self.tag.clone();
            self.tail.clear();
        } else {
            self.mode = Mode::Text;
        }
    }

    fn feed(&mut self, c: char) {
        let lower = c.to_ascii_lowercase();
        match self.mode {
            Mode::Text => {
                if c == '<' {
                    self.mode = Mode::Lt;
                }
            }
            Mode::Lt => {
                if c.is_ascii_alphabetic() {
                    self.mode = Mode::TagName;
                    self.tag = lower.to_string();
                    self.attr.clear();
                } else if c == '/' {
                    self.mode = Mode::EndOpen;
                } else if c == '!' {
                    self.mode = Mode::Bang;
                    self.dashes = 0;
                } else if c == '?' {
                    self.mode = Mode::Decl;
                } else if c != '<' {
                    self.mode = Mode::Text;
                }
            }
            Mode::EndOpen => {
                if c.is_ascii_alphabetic() {
                    self.mode = Mode::EndTag;
                } else if c == '>' {
                    self.mode = Mode::Text;
                } else {
                    self.mode = Mode::Decl;
                }
            }
            Mode::Bang => {
                if c == '-' {
                    self.dashes += 1;
                    if self.dashes == 2 {
                        self.mode = Mode::Comment;
                        self.tail.clear();
                    }
                } else if c == '>' {
                    self.mode = Mode::Text;
                } else {
                    self.mode = Mode::Decl;
                }
            }
            Mode::Comment => {
                self.tail.push(c);
                trim_tail(&mut self.tail, 3);
                if self.tail.ends_with("-->") {
                    self.mode = Mode::Text;
                }
            }
            Mode::Decl | Mode::EndTag => {
                if c == '>' {
                    self.mode = Mode::Text;
                }
            }
            Mode::TagName => {
                if c.is_whitespace() || c == '/' {
                    self.mode = Mode::InTag;
                } else if c == '>' {
                    self.finish_tag();
                } else {
                    self.tag.push(lower);
                }
            }
            Mode::InTag => {
                if c.is_whitespace() || c == '/' {
                } else if c == '>' {
                    self.finish_tag();
                } else {
                    self.mode = Mode::AttrName;
                    self.attr = lower.to_string();
                }
            }
            Mode::AttrName => {
                if c.is_whitespace() {
                    self.mode = Mode::AfterAttrName;
                } else if c == '=' {
                    self.mode = Mode::BeforeValue;
                } else if c == '/' {
                    self.mode = Mode::InTag;
                } else if c == '>' {
                    self.finish_tag();
                } else {
                    self.attr.push(lower);
                }
            }
            Mode::AfterAttrName => {
                if c.is_whitespace() {
                } else if c == '=' {
                    self.mode = Mode::BeforeValue;
                } else if c == '>' {
                    self.finish_tag();
                } else if c == '/' {
                    self.mode = Mode::InTag;
                } else {
                    self.mode = Mode::AttrName;
                    self.attr = lower.to_string();
                }
            }
            Mode::BeforeValue => {
                if c.is_whitespace() {
                } else if c == '"' {
                    self.mode = Mode::ValueDq;
                } else if c == '\'' {
                    self.mode = Mode::ValueSq;
                } else if c == '>' {
                    self.finish_tag();
                } else {
                    self.mode = Mode::ValueUnquoted;
                }
            }
            Mode::ValueDq => {
                if c == '"' {
                    self.mode = Mode::InTag;
                }
            }
            Mode::ValueSq => {
                if c == '\'' {
                    self.mode = Mode::InTag;
                }
            }
            Mode::ValueUnquoted => {
                if c.is_whitespace() {
                    self.mode = Mode::InTag;
                } else if c == '>' {
                    self.finish_tag();
                }
            }
            Mode::Raw => {
                let closer = format!("</{}", self.raw);
                if (c.is_whitespace() || c == '/' || c == '>') && self.tail.ends_with(&closer) {
                    self.tail.clear();
                    self.raw.clear();
                    self.mode = if c == '>' { Mode::Text } else { Mode::EndTag };
                } else {
                    self.tail.push(lower);
                    trim_tail(&mut self.tail, closer.chars().count() + 1);
                }
            }
        }
    }

    fn break_adjacency(&mut self) {
        self.tail.clear();
    }
}

fn trim_tail(tail: &mut String, keep: usize) {
    let count = tail.chars().count();
    if count > keep {
        *tail = tail.chars().skip(count - keep).collect();
    }
}

const URL_ATTRIBUTES: &[&str] = &[
    "href",
    "src",
    "action",
    "formaction",
    "cite",
    "data",
    "poster",
    "background",
    "ping",
    "manifest",
    "codebase",
    "longdesc",
    "usemap",
    "icon",
    "profile",
    "classid",
    "archive",
    "xlink:href",
    "itemtype",
    "itemid",
];

/// The error code, if any, for an interpolation of `kind` at the tokenizer's current position.
fn context_error(state: &Html, kind: Kind) -> Option<(&'static str, String)> {
    use Kind::*;
    let name = match kind {
        Body => "{{ x }}",
        Attr => "{{ attr x }}",
        Url => "{{ url x }}",
        Script => "{{ script x }}",
        Embed => "{{ embed x }}",
    };
    match state.mode {
        Mode::Text => match kind {
            Script => Some(("ScriptOutsideScript", format!("`{name}` renders a JavaScript string and belongs inside a <script> element; in text use `{{{{ x }}}}`"))),
            _ => None,
        },
        Mode::ValueDq | Mode::ValueSq => {
            let attr = state.attr.as_str();
            if attr.starts_with("on") || attr == "style" || attr == "srcdoc" || attr == "srcset" {
                return Some(("AttributeCodeContext", format!("`{name}` is inside the `{attr}` attribute, which holds code or markup; HTML escaping does not make a value safe there, so pass the value through a data attribute or build it in the template text")));
            }
            let is_url = URL_ATTRIBUTES.contains(&attr);
            match kind {
                Script => Some(("ScriptOutsideScript", format!("`{name}` renders a JavaScript string and belongs inside a <script> element"))),
                Embed => Some(("EmbedContext", "`embed` inserts markup and is allowed only in element text, not in an attribute value".to_owned())),
                Body | Attr if is_url => Some(("UrlContext", format!("`{name}` is inside the `{attr}` attribute, a URL: HTML escaping would let `javascript:` through; use `{{{{ url x }}}}` after a literal prefix such as `/items/`"))),
                _ => None,
            }
        }
        Mode::Raw => {
            if state.raw == "script" {
                match kind {
                    Script => None,
                    Embed => Some(("EmbedContext", "`embed` inserts markup and is allowed only in element text, not inside <script>".to_owned())),
                    _ => Some(("ScriptContext", format!("`{name}` is inside a <script> element, where HTML escaping is not enough; write `{{{{ script x }}}}`, which renders a JSON string literal"))),
                }
            } else {
                Some(("StyleContext", format!("`{name}` is inside a <style> element; CSS values are not supported, put the value in a class or a data attribute")))
            }
        }
        Mode::Comment => Some(("CommentContext", format!("`{name}` is inside an HTML comment"))),
        Mode::BeforeValue | Mode::ValueUnquoted => Some(("UnquotedAttribute", format!("`{name}` is an unquoted attribute value; quote the attribute (`name=\"{{{{ x }}}}\"`)"))),
        Mode::Lt | Mode::EndOpen | Mode::Bang | Mode::Decl | Mode::TagName | Mode::EndTag | Mode::InTag | Mode::AttrName | Mode::AfterAttrName => {
            Some(("TagContext", format!("`{name}` is inside a tag, at a place that is neither element text nor a quoted attribute value (tag names, attribute names and `<!...>` declarations cannot be interpolated)")))
        }
    }
}


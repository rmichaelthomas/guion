//! Checked templates: the pre-pass that turns `NAME.gut` files into ordinary Guion modules.
//!
//! A template compiles to `NAME.gut.gu` next to it: a module with one function,
//! `render_NAME(parameters) -> Rendered`, written against the escapers of the `web` package. The
//! compiler, the self-hosted compiler and the artifact format never see a template, so no template
//! parser exists in a compiled program. The pre-pass runs before compilation in every command that
//! compiles a project. See `docs/templates.md` for the user-facing description.

use guion_model::{Diagnostic, Span};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

/// The first line of every generated module.
pub const MARKER: &str = "# generated by guion from ";
/// The suffix of a generated module; the exact line kept in the directory's `.gitignore`.
pub const GENERATED_SUFFIX: &str = ".gut.gu";
const GUT_SUFFIX: &str = ".gut";
const WALK_DEPTH: usize = 12;

/// A template problem: a stable code, the file it is in (relative to the project root), and a
/// 1-based line and column in characters.
#[derive(Debug, Clone)]
pub struct TemplateError {
    pub code: &'static str,
    pub message: String,
    pub file: String,
    pub line: usize,
    pub column: usize,
}

impl TemplateError {
    fn at(code: &'static str, message: impl Into<String>, file: &str, pos: Pos) -> Self {
        Self {
            code,
            message: message.into(),
            file: file.to_owned(),
            line: pos.0,
            column: pos.1,
        }
    }

    /// The code as shown: `TEMPLATE_` and the variant name in capitals with underscores. Variant
    /// names are kept in CamelCase in the source so the generated agent reference, which scans
    /// source text for `E_` and `R_` tokens, does not list pieces of template codes.
    pub fn full_code(&self) -> String {
        let mut text = String::from("TEMPLATE");
        for c in self.code.chars() {
            if c.is_ascii_uppercase() {
                text.push('_');
            }
            text.push(c.to_ascii_uppercase());
        }
        text
    }

    pub fn to_diagnostic(&self) -> Diagnostic {
        let mut diagnostic = Diagnostic::new(
            self.full_code(),
            self.message.clone(),
            Span {
                source_id: 0,
                start: 0,
                end: 0,
                line: self.line,
                column: self.column,
            },
        );
        diagnostic.source_name = Some(self.file.clone());
        diagnostic
    }
}

type Pos = (usize, usize);


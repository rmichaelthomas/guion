struct Checker<'a> {
    file: &'a str,
    known: &'a BTreeSet<String>,
    scope: Vec<String>,
    html: Html,
    references: Vec<(String, Pos)>,
}

impl Checker<'_> {
    fn path(&self, path: &VarPath) -> Result<(), TemplateError> {
        if !self.scope.contains(&path.names[0]) {
            return Err(TemplateError::at(
                "UnknownVariable",
                format!("`{}` is not a parameter or a loop variable of this template; declare it in `{{% params ... %}}`", path.names[0]),
                self.file,
                path.pos,
            ));
        }
        Ok(())
    }

    fn nodes(&mut self, nodes: &[Node]) -> Result<(), TemplateError> {
        for node in nodes {
            match node {
                Node::Text(text, _) => {
                    for c in text.chars() {
                        self.html.feed(c);
                    }
                }
                Node::Interp { kind, expr, pos } => {
                    match expr {
                        Expr::Path(path) => self.path(path)?,
                        Expr::Call {
                            name,
                            pos: name_pos,
                            args,
                        } => {
                            if !self.known.contains(name) {
                                return Err(TemplateError::at(
                                    "UnknownFunction",
                                    format!("`{name}` is not a template in this directory; `embed` calls a sibling `{name}.gut`"),
                                    self.file,
                                    *name_pos,
                                ));
                            }
                            for arg in args {
                                self.path(arg)?;
                            }
                            self.references.push((name.clone(), *name_pos));
                        }
                    }
                    if let Some((code, message)) = context_error(&self.html, *kind) {
                        return Err(TemplateError::at(code, message, self.file, *pos));
                    }
                    self.html.break_adjacency();
                }
                Node::For {
                    var,
                    var_pos,
                    list,
                    body,
                    pos,
                } => {
                    self.path(list)?;
                    self.declare(var, *var_pos)?;
                    let before = self.html.clone();
                    self.scope.push(var.clone());
                    self.nodes(body)?;
                    self.scope.pop();
                    if self.html != before {
                        return Err(mismatch(self.file, *pos));
                    }
                    self.html.break_adjacency();
                }
                Node::If {
                    cond,
                    then,
                    otherwise,
                    pos,
                    ..
                } => {
                    self.path(cond)?;
                    let before = self.html.clone();
                    self.nodes(then)?;
                    if self.html != before {
                        return Err(mismatch(self.file, *pos));
                    }
                    if let Some(otherwise) = otherwise {
                        self.nodes(otherwise)?;
                        if self.html != before {
                            return Err(mismatch(self.file, *pos));
                        }
                    }
                    self.html.break_adjacency();
                }
            }
        }
        Ok(())
    }

    fn declare(&self, name: &str, pos: Pos) -> Result<(), TemplateError> {
        if let Some(why) = reserved_name(name) {
            return Err(TemplateError::at(
                "ReservedName",
                format!("`{name}` is {why}; pick another loop variable name"),
                self.file,
                pos,
            ));
        }
        if self.scope.iter().any(|existing| existing == name) {
            return Err(TemplateError::at(
                "DuplicateVariable",
                format!("`{name}` is already a parameter or an enclosing loop variable"),
                self.file,
                pos,
            ));
        }
        Ok(())
    }
}

fn mismatch(file: &str, pos: Pos) -> TemplateError {
    TemplateError::at(
        "ContextMismatch",
        "this block leaves the HTML in a different state than it found it (a tag or an attribute value is opened and not closed inside the block), so an interpolation after it would have no single context",
        file,
        pos,
    )
}

fn literal(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20
                || (0x7f..=0x9f).contains(&(c as u32))
                || matches!(c as u32, 0x2028 | 0x2029 | 0xfeff) =>
            {
                out.push_str(&format!("\\u{{{:X}}}", c as u32));
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

struct Generator {
    lines: Vec<String>,
    pending: String,
    pending_pos: Pos,
}

impl Generator {
    fn line(&mut self, depth: usize, text: &str, pos: Pos) {
        self.lines.push(format!(
            "{}{text}  # gut:{}:{}",
            "    ".repeat(depth),
            pos.0,
            pos.1
        ));
    }

    fn flush(&mut self, depth: usize) {
        if !self.pending.is_empty() {
            let text = std::mem::take(&mut self.pending);
            let pos = self.pending_pos;
            self.line(
                depth,
                &format!("set gut_out = list_push(gut_out, {})", literal(&text)),
                pos,
            );
        }
    }

    fn nodes(&mut self, nodes: &[Node], depth: usize) {
        for node in nodes {
            match node {
                Node::Text(text, pos) => {
                    if self.pending.is_empty() {
                        self.pending_pos = *pos;
                    }
                    self.pending.push_str(text);
                }
                Node::Interp { kind, expr, pos } => {
                    let argument = match expr {
                        Expr::Path(path) => path.code(),
                        Expr::Call { name, args, .. } => format!(
                            "render_{name}({})",
                            args.iter()
                                .map(VarPath::code)
                                .collect::<Vec<_>>()
                                .join(", ")
                        ),
                    };
                    let value = match kind {
                        Kind::Body => format!("html_escape_text({argument})"),
                        Kind::Attr => format!("html_escape_attr({argument})"),
                        Kind::Url => format!("html_escape_url({argument})"),
                        Kind::Script => format!("html_script_string({argument})"),
                        Kind::Embed => format!("html_embed_rendered({argument})"),
                    };
                    let text = std::mem::take(&mut self.pending);
                    let expression = if text.is_empty() {
                        value
                    } else {
                        format!("{} + {value}", literal(&text))
                    };
                    self.line(
                        depth,
                        &format!("set gut_out = list_push(gut_out, {expression})"),
                        *pos,
                    );
                }
                Node::For {
                    var,
                    list,
                    body,
                    pos,
                    ..
                } => {
                    self.flush(depth);
                    self.line(depth, &format!("for {var} in {}:", list.code()), *pos);
                    self.block(body, depth + 1, *pos);
                }
                Node::If {
                    negate,
                    cond,
                    then,
                    otherwise,
                    pos,
                } => {
                    self.flush(depth);
                    let condition = if *negate {
                        format!("not {}", cond.code())
                    } else {
                        cond.code()
                    };
                    self.line(depth, &format!("if {condition}:"), *pos);
                    self.block(then, depth + 1, *pos);
                    if let Some(otherwise) = otherwise {
                        self.line(depth, "else:", *pos);
                        self.block(otherwise, depth + 1, *pos);
                    }
                }
            }
        }
    }

    fn block(&mut self, nodes: &[Node], depth: usize, pos: Pos) {
        let start = self.lines.len();
        self.nodes(nodes, depth);
        self.flush(depth);
        if self.lines.len() == start {
            self.line(depth, "let gut_noop = 0", pos);
        }
    }
}

fn compile_template(
    source: &str,
    file: &str,
    stem: &str,
    known: &BTreeSet<String>,
) -> Result<Compiled, TemplateError> {
    let template = parse(source, file)?;
    let mut checker = Checker {
        file,
        known,
        scope: template
            .params
            .iter()
            .map(|param| param.name.clone())
            .collect(),
        html: Html::new(),
        references: Vec::new(),
    };
    checker.nodes(&template.body)?;
    let mut generator = Generator {
        lines: Vec::new(),
        pending: String::new(),
        pending_pos: (1, 1),
    };
    generator.nodes(&template.body, 1);
    generator.flush(1);
    let name = file.rsplit('/').next().unwrap_or(file);
    let mut code = format!("{MARKER}{name}; do not edit; do not commit\n");
    code.push_str("pub import \"pkg:web/src/html.gu\"\n");
    for (path, pos) in &template.imports {
        code.push_str(&format!("import \"{path}\"  # gut:{}:{}\n", pos.0, pos.1));
    }
    let mut referenced = BTreeSet::new();
    for (reference, _) in &checker.references {
        if referenced.insert(reference.clone()) {
            code.push_str(&format!("import \"{reference}{GENERATED_SUFFIX}\"\n"));
        }
    }
    let parameters = template
        .params
        .iter()
        .map(|param| format!("{}: {}", param.name, param.ty))
        .collect::<Vec<_>>()
        .join(", ");
    code.push_str(&format!(
        "\npub fn render_{stem}({parameters}) -> Rendered:  # gut:{}:{}\n",
        template.params_pos.0, template.params_pos.1
    ));
    code.push_str("    var gut_out: List[Text] = []\n");
    for line in &generator.lines {
        code.push_str(line);
        code.push('\n');
    }
    code.push_str("    return html_finish(gut_out)\n");
    Ok(Compiled {
        code,
        references: checker.references,
    })
}

fn check_cycles(root: &Path, compiled: &[(PathBuf, Compiled)]) -> Result<(), TemplateError> {
    let mut graph: BTreeMap<(PathBuf, String), &Compiled> = BTreeMap::new();
    for (path, template) in compiled {
        graph.insert(
            (path.parent().unwrap().to_path_buf(), template_stem(path)),
            template,
        );
    }
    for (path, template) in compiled {
        let directory = path.parent().unwrap().to_path_buf();
        let start = template_stem(path);
        let mut seen = BTreeSet::new();
        let mut work = template
            .references
            .iter()
            .map(|(name, pos)| (name.clone(), *pos))
            .collect::<Vec<_>>();
        while let Some((name, pos)) = work.pop() {
            if name == start {
                return Err(TemplateError::at(
                    "Cycle",
                    format!("`{start}` embeds itself through `{name}`; templates cannot call each other in a cycle"),
                    &relative(root, path),
                    pos,
                ));
            }
            if !seen.insert(name.clone()) {
                continue;
            }
            if let Some(next) = graph.get(&(directory.clone(), name)) {
                work.extend(next.references.iter().map(|(name, _)| (name.clone(), pos)));
            }
        }
    }
    Ok(())
}

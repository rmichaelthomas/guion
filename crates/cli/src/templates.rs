#[derive(Default)]
struct Found {
    templates: Vec<PathBuf>,
    generated: Vec<PathBuf>,
    sources: Vec<PathBuf>,
}

fn walk(directory: &Path, depth: usize, found: &mut Found) {
    if depth > WALK_DEPTH {
        return;
    }
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    let mut entries = entries
        .flatten()
        .map(|entry| entry.path())
        .collect::<Vec<_>>();
    entries.sort();
    for path in entries {
        let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        if path.is_dir() {
            if name.starts_with('.') || name == "target" || name == "node_modules" {
                continue;
            }
            walk(&path, depth + 1, found);
        } else if name.ends_with(GENERATED_SUFFIX) {
            found.generated.push(path);
        } else if name.ends_with(GUT_SUFFIX) {
            found.templates.push(path);
        } else if name.ends_with(".gu") {
            found.sources.push(path);
        }
    }
}

fn sibling_stems(templates: &[PathBuf]) -> BTreeMap<PathBuf, BTreeSet<String>> {
    let mut map: BTreeMap<PathBuf, BTreeSet<String>> = BTreeMap::new();
    for path in templates {
        map.entry(path.parent().unwrap().to_path_buf())
            .or_default()
            .insert(template_stem(path));
    }
    map
}

/// A generated module whose template is gone is removed. Only files that carry the marker are
/// ever removed, so a hand-written `*.gut.gu` is left alone.
fn remove_stale(found: &Found) -> Result<(), TemplateError> {
    for path in &found.generated {
        let Ok(text) = fs::read_to_string(path) else {
            continue;
        };
        if !is_generated(&text) {
            continue;
        }
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or("");
        let template = path.with_file_name(&name[..name.len() - 3]);
        if !template.is_file() {
            fs::remove_file(path).map_err(|error| io_error(path, &error))?;
        }
    }
    Ok(())
}

fn write_generated(template: &Path, code: &str) -> Result<(), TemplateError> {
    let target = template.with_file_name(format!("{}{GENERATED_SUFFIX}", template_stem(template)));
    if fs::read_to_string(&target).is_ok_and(|existing| existing == code) {
        ensure_ignored(target.parent().unwrap())?;
        return Ok(());
    }
    if let Ok(existing) = fs::read_to_string(&target) {
        if !is_generated(&existing) {
            return Err(TemplateError::at(
                "OutputExists",
                format!(
                    "{} exists and was not generated by guion; rename it so the template can write there",
                    target.display()
                ),
                &template.to_string_lossy(),
                (1, 1),
            ));
        }
    }
    fs::write(&target, code).map_err(|error| io_error(&target, &error))?;
    ensure_ignored(target.parent().unwrap())
}

/// Keeps one line, `*.gut.gu`, in the `.gitignore` of the directory that holds generated modules.
fn ensure_ignored(directory: &Path) -> Result<(), TemplateError> {
    let path = directory.join(".gitignore");
    let existing = fs::read_to_string(&path).unwrap_or_default();
    if existing
        .lines()
        .any(|line| line.trim() == format!("*{GENERATED_SUFFIX}"))
    {
        return Ok(());
    }
    let mut text = existing;
    if !text.is_empty() && !text.ends_with('\n') {
        text.push('\n');
    }
    text.push_str(&format!("*{GENERATED_SUFFIX}\n"));
    fs::write(&path, text).map_err(|error| io_error(&path, &error))
}


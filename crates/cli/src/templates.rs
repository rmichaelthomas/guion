/// Whether `text` is a module this pre-pass generated.
pub fn is_generated(text: &str) -> bool {
    text.starts_with(MARKER)
}

/// Runs the pre-pass for the project that contains `entry`. It does nothing for an artifact, for a
/// source outside a project (no `guion.toml`), and for a project with no templates.
pub fn prepass(entry: &Path, project_root: &Path) -> Result<(), TemplateError> {
    if entry.extension().and_then(|extension| extension.to_str()) != Some("gu") {
        return Ok(());
    }
    if !project_root.join("guion.toml").is_file() {
        return Ok(());
    }
    let root = fs::canonicalize(project_root).map_err(|error| io_error(project_root, &error))?;
    let entry = fs::canonicalize(entry).map_err(|error| io_error(entry, &error))?;
    let directory = entry.parent().unwrap_or(&root);
    if !directory.starts_with(&root) {
        return Ok(());
    }
    let mut found = Found::default();
    walk(directory, 0, &mut found);
    remove_stale(&found)?;
    if found.templates.is_empty() {
        return Ok(());
    }
    let first = relative(&root, &found.templates[0]);
    if !project_depends_on_web(&root) {
        return Err(TemplateError::at(
            "RuntimeMissing",
            "templates compile against the `web` package, which this project does not depend on; run `guion add web`",
            &first,
            (1, 1),
        ));
    }
    let mut compiled = Vec::new();
    let siblings = sibling_stems(&found.templates);
    for path in &found.templates {
        let file = relative(&root, path);
        let source = fs::read_to_string(path).map_err(|error| io_error(path, &error))?;
        let stem = template_stem(path);
        if !is_identifier(&stem) {
            return Err(TemplateError::at(
                "BadName",
                format!("`{stem}` is not an identifier, so no function `render_{stem}` can be written; rename the template to letters, digits and underscores"),
                &file,
                (1, 1),
            ));
        }
        let known = siblings
            .get(path.parent().unwrap())
            .cloned()
            .unwrap_or_default();
        compiled.push((
            path.clone(),
            compile_template(&source, &file, &stem, &known)?,
        ));
    }
    check_cycles(&root, &compiled)?;
    forbid_forged_rendered(&root, &found)?;
    for (path, template) in &compiled {
        write_generated(path, &template.code)?;
    }
    Ok(())
}

/// Rewrites a compiler diagnostic that points into a generated module so that it points at the
/// template line and column the generated line came from.
pub fn remap(mut error: Diagnostic, project_root: &Path) -> Diagnostic {
    let Some(name) = error.source_name.clone() else {
        return error;
    };
    if !name.ends_with(GENERATED_SUFFIX) {
        return error;
    }
    let Ok(text) = fs::read_to_string(project_root.join(&name)) else {
        return error;
    };
    if !is_generated(&text) {
        return error;
    }
    let lines = text.lines().collect::<Vec<_>>();
    let mut index = error.span.line.min(lines.len()).saturating_sub(1);
    let mut mapped = None;
    loop {
        if let Some(position) = lines.get(index).and_then(|line| marker_of(line)) {
            mapped = Some(position);
            break;
        }
        if index == 0 {
            break;
        }
        index -= 1;
    }
    let (line, column) = mapped.unwrap_or((1, 1));
    error.source_name = Some(name[..name.len() - 3].to_owned());
    error.span.line = line;
    error.span.column = column;
    error
}

fn marker_of(line: &str) -> Option<Pos> {
    let (_, tail) = line.rsplit_once("# gut:")?;
    let (line, column) = tail.trim().split_once(':')?;
    Some((line.parse().ok()?, column.parse().ok()?))
}

fn io_error(path: &Path, error: &std::io::Error) -> TemplateError {
    TemplateError::at(
        "Io",
        format!("cannot read or write {}: {error}", path.display()),
        &path.to_string_lossy(),
        (1, 1),
    )
}

fn relative(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

fn template_stem(path: &Path) -> String {
    let name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("");
    name.strip_suffix(GUT_SUFFIX).unwrap_or(name).to_owned()
}

fn project_depends_on_web(root: &Path) -> bool {
    let Ok(manifest) = fs::read_to_string(root.join("guion.toml")) else {
        return false;
    };
    let Ok(document) = toml::from_str::<toml::Value>(&manifest) else {
        return false;
    };
    document
        .get("dependencies")
        .and_then(toml::Value::as_table)
        .is_some_and(|dependencies| dependencies.contains_key("web"))
}


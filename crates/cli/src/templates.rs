/// In a project that uses templates, a hand-written module may not make a `Rendered` or reach for
/// the functions that generated code uses to make or open one. The language has no private fields,
/// so this is the check that keeps `Rendered` unforgeable.
fn forbid_forged_rendered(root: &Path, found: &Found) -> Result<(), TemplateError> {
    for path in &found.sources {
        let Ok(text) = fs::read_to_string(path) else {
            continue;
        };
        if text.contains("record Rendered:") || is_generated(&text) {
            continue;
        }
        let file = relative(root, path);
        let chars = text.chars().collect::<Vec<_>>();
        let (mut line, mut column) = (1usize, 1usize);
        let mut index = 0;
        let mut in_string = false;
        while index < chars.len() {
            let c = chars[index];
            if in_string {
                if c == '\\' {
                    advance(&chars, &mut index, &mut line, &mut column);
                } else if c == '"' || c == '\n' {
                    in_string = false;
                }
                advance(&chars, &mut index, &mut line, &mut column);
                continue;
            }
            if c == '"' {
                in_string = true;
                advance(&chars, &mut index, &mut line, &mut column);
                continue;
            }
            if c == '#' {
                while index < chars.len() && chars[index] != '\n' {
                    advance(&chars, &mut index, &mut line, &mut column);
                }
                continue;
            }
            if c.is_ascii_alphabetic() || c == '_' {
                let start = (line, column);
                let begin = index;
                while index < chars.len()
                    && (chars[index].is_ascii_alphanumeric() || chars[index] == '_')
                {
                    advance(&chars, &mut index, &mut line, &mut column);
                }
                let word = chars[begin..index].iter().collect::<String>();
                let mut after = index;
                while after < chars.len() && (chars[after] == ' ' || chars[after] == '\t') {
                    after += 1;
                }
                let forged = match word.as_str() {
                    "html_finish" | "html_embed_rendered" => true,
                    "Rendered" => chars.get(after) == Some(&'('),
                    _ => false,
                };
                if forged {
                    return Err(TemplateError::at(
                        "RenderedForgery",
                        format!("`{word}` is for generated template code: a `Rendered` value is made only by a template, so build markup in a `.gut` file; read its text with `.html`"),
                        &file,
                        start,
                    ));
                }
                continue;
            }
            advance(&chars, &mut index, &mut line, &mut column);
        }
    }
    Ok(())
}

fn advance(chars: &[char], index: &mut usize, line: &mut usize, column: &mut usize) {
    if chars[*index] == '\n' {
        *line += 1;
        *column = 1;
    } else {
        *column += 1;
    }
    *index += 1;
}


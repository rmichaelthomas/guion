#[derive(Clone, Debug)]
struct VarPath {
    names: Vec<String>,
    pos: Pos,
}

impl VarPath {
    fn code(&self) -> String {
        self.names.join(".")
    }
}

#[derive(Clone, Debug)]
enum Expr {
    Path(VarPath),
    Call {
        name: String,
        pos: Pos,
        args: Vec<VarPath>,
    },
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    Body,
    Attr,
    Url,
    Script,
    Embed,
}

#[derive(Clone, Debug)]
enum Node {
    Text(String, Pos),
    Interp {
        kind: Kind,
        expr: Expr,
        pos: Pos,
    },
    For {
        var: String,
        var_pos: Pos,
        list: VarPath,
        body: Vec<Node>,
        pos: Pos,
    },
    If {
        negate: bool,
        cond: VarPath,
        then: Vec<Node>,
        otherwise: Option<Vec<Node>>,
        pos: Pos,
    },
}

struct Param {
    name: String,
    ty: String,
}

struct Template {
    imports: Vec<(String, Pos)>,
    params: Vec<Param>,
    params_pos: Pos,
    body: Vec<Node>,
}

pub struct Compiled {
    code: String,
    /// Sibling templates this one embeds, with the position of the call.
    references: Vec<(String, Pos)>,
}

const KEYWORDS: &[&str] = &[
    "fn", "let", "var", "set", "return", "if", "else", "while", "for", "in", "match", "break",
    "continue", "true", "false", "not", "and", "or", "import", "pub", "record", "None", "Some",
    "Ok", "Err",
];

fn is_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// Names the generated body itself refers to, which a template variable may not take.
fn reserved_name(name: &str) -> Option<&'static str> {
    if KEYWORDS.contains(&name) {
        return Some("a Guion keyword");
    }
    if name.starts_with("html_") || name.starts_with("gut_") {
        return Some("a prefix generated code uses (`html_`, `gut_`)");
    }
    if name == "list_push" || name == "Rendered" {
        return Some("a name generated code uses");
    }
    None
}

// ---------------------------------------------------------------------------------------------
// Lexing
// ---------------------------------------------------------------------------------------------

enum Piece {
    Text(String, Pos),
    Expr { body: Vec<(char, Pos)>, pos: Pos },
    Stmt { body: Vec<(char, Pos)>, pos: Pos },
}

fn lex(source: &str, file: &str) -> Result<Vec<Piece>, TemplateError> {
    let chars = source.chars().collect::<Vec<_>>();
    let mut positions = Vec::with_capacity(chars.len() + 1);
    let (mut line, mut column) = (1usize, 1usize);
    for &c in &chars {
        positions.push((line, column));
        if c == '\n' {
            line += 1;
            column = 1;
        } else {
            column += 1;
        }
    }
    positions.push((line, column));
    let mut pieces = Vec::new();
    let mut text = String::new();
    let mut text_pos = (1, 1);
    let mut index = 0;
    while index < chars.len() {
        let c = chars[index];
        let next = chars.get(index + 1).copied();
        let is_open = c == '{' && (next == Some('{') || next == Some('%'));
        if c == '\\'
            && chars.get(index + 1) == Some(&'{')
            && matches!(chars.get(index + 2), Some('{') | Some('%'))
        {
            if text.is_empty() {
                text_pos = positions[index];
            }
            text.push('{');
            text.push(chars[index + 2]);
            index += 3;
            continue;
        }
        if !is_open {
            if text.is_empty() {
                text_pos = positions[index];
            }
            text.push(c);
            index += 1;
            continue;
        }
        if !text.is_empty() {
            pieces.push(Piece::Text(std::mem::take(&mut text), text_pos));
        }
        let (closer, is_expr) = if next == Some('{') {
            ("}}", true)
        } else {
            ("%}", false)
        };
        let start = index;
        let mut cursor = index + 2;
        let mut end = None;
        while cursor + 1 < chars.len() {
            if chars[cursor] == closer.chars().next().unwrap()
                && chars[cursor + 1] == closer.chars().nth(1).unwrap()
            {
                end = Some(cursor);
                break;
            }
            cursor += 1;
        }
        let Some(end) = end else {
            return Err(TemplateError::at(
                "UnclosedTag",
                format!(
                    "`{}` is never closed with `{closer}`",
                    if is_expr { "{{" } else { "{%" }
                ),
                file,
                positions[start],
            ));
        };
        let body = (start + 2..end).map(|i| (chars[i], positions[i])).collect();
        let pos = positions[start];
        if is_expr {
            pieces.push(Piece::Expr { body, pos });
        } else {
            pieces.push(Piece::Stmt { body, pos });
        }
        index = end + 2;
    }
    if !text.is_empty() {
        pieces.push(Piece::Text(text, text_pos));
    }
    Ok(pieces)
}

#[derive(Debug, Clone, PartialEq)]
enum Tok {
    Ident(String),
    Dot,
    LParen,
    RParen,
    Comma,
    Other(char),
}

fn tokens(body: &[(char, Pos)]) -> Vec<(Tok, Pos)> {
    let mut result = Vec::new();
    let mut index = 0;
    while index < body.len() {
        let (c, pos) = body[index];
        if c.is_whitespace() {
            index += 1;
        } else if c.is_ascii_alphabetic() || c == '_' {
            let mut word = String::new();
            while index < body.len()
                && (body[index].0.is_ascii_alphanumeric() || body[index].0 == '_')
            {
                word.push(body[index].0);
                index += 1;
            }
            result.push((Tok::Ident(word), pos));
        } else {
            result.push((
                match c {
                    '.' => Tok::Dot,
                    '(' => Tok::LParen,
                    ')' => Tok::RParen,
                    ',' => Tok::Comma,
                    other => Tok::Other(other),
                },
                pos,
            ));
            index += 1;
        }
    }
    result
}

fn describe(token: &Tok) -> String {
    match token {
        Tok::Ident(name) => format!("`{name}`"),
        Tok::Dot => "`.`".into(),
        Tok::LParen => "`(`".into(),
        Tok::RParen => "`)`".into(),
        Tok::Comma => "`,`".into(),
        Tok::Other(c) => format!("`{c}`"),
    }
}

fn parse_path(
    toks: &[(Tok, Pos)],
    at: &mut usize,
    file: &str,
    tag: Pos,
) -> Result<VarPath, TemplateError> {
    let start = toks.get(*at).map(|(_, pos)| *pos).unwrap_or(tag);
    let mut names = Vec::new();
    loop {
        match toks.get(*at) {
            Some((Tok::Ident(name), _)) => {
                names.push(name.clone());
                *at += 1;
            }
            _ => {
                return Err(TemplateError::at(
                    "BadExpression",
                    "expected a variable name, or `name.field`",
                    file,
                    start,
                ))
            }
        }
        if matches!(toks.get(*at), Some((Tok::Dot, _))) {
            *at += 1;
        } else {
            break;
        }
    }
    Ok(VarPath { names, pos: start })
}

fn expect_end(toks: &[(Tok, Pos)], at: usize, file: &str) -> Result<(), TemplateError> {
    if let Some((token, pos)) = toks.get(at) {
        return Err(TemplateError::at(
            "BadExpression",
            format!(
                "unexpected {} here; a tag holds a variable, an interpolator and a variable, or a block header (there is no filter or expression syntax)",
                describe(token)
            ),
            file,
            *pos,
        ));
    }
    Ok(())
}

// ---------------------------------------------------------------------------------------------
// Parsing
// ---------------------------------------------------------------------------------------------

enum Frame {
    For {
        var: String,
        var_pos: Pos,
        list: VarPath,
        pos: Pos,
        nodes: Vec<Node>,
    },
    If {
        negate: bool,
        cond: VarPath,
        pos: Pos,
        nodes: Vec<Node>,
        then: Option<Vec<Node>>,
    },
}

impl Frame {
    fn nodes(&mut self) -> &mut Vec<Node> {
        match self {
            Frame::For { nodes, .. } | Frame::If { nodes, .. } => nodes,
        }
    }

    fn pos(&self) -> Pos {
        match self {
            Frame::For { pos, .. } | Frame::If { pos, .. } => *pos,
        }
    }
}

fn parse(source: &str, file: &str) -> Result<Template, TemplateError> {
    let pieces = lex(source, file)?;
    let mut imports = Vec::new();
    let mut params: Option<(Vec<Param>, Pos)> = None;
    let mut in_header = true;
    let mut root: Vec<Node> = Vec::new();
    let mut stack: Vec<Frame> = Vec::new();
    let mut swallow_break = false;
    for piece in pieces {
        match piece {
            Piece::Text(mut text, pos) => {
                if swallow_break {
                    swallow_break = false;
                    let trimmed = text.trim_start_matches([' ', '\t']);
                    if let Some(rest) = trimmed
                        .strip_prefix("\r\n")
                        .or_else(|| trimmed.strip_prefix('\n'))
                    {
                        text = rest.to_owned();
                    }
                    if text.is_empty() {
                        continue;
                    }
                }
                if in_header {
                    if text.chars().all(char::is_whitespace) {
                        continue;
                    }
                    in_header = false;
                }
                push(&mut root, &mut stack, Node::Text(text, pos));
            }
            Piece::Expr { body, pos } => {
                in_header = false;
                swallow_break = false;
                let toks = tokens(&body);
                let Some((first, first_pos)) = toks.first().cloned() else {
                    return Err(TemplateError::at(
                        "BadExpression",
                        "an empty tag; write `{{ name }}`",
                        file,
                        pos,
                    ));
                };
                let interpolator = match (&first, toks.get(1)) {
                    (Tok::Ident(word), Some((Tok::Ident(_), _)))
                        if matches!(word.as_str(), "attr" | "url" | "script" | "embed") =>
                    {
                        Some(match word.as_str() {
                            "attr" => Kind::Attr,
                            "url" => Kind::Url,
                            "script" => Kind::Script,
                            _ => Kind::Embed,
                        })
                    }
                    (Tok::Ident(word), Some((Tok::Ident(_), _))) => {
                        return Err(TemplateError::at(
                            "UnknownInterpolator",
                            format!(
                                "`{word}` is not an interpolator; the interpolators are `attr`, `url`, `script` and `embed`, and there is no way to switch escaping off"
                            ),
                            file,
                            first_pos,
                        ));
                    }
                    _ => None,
                };
                let (kind, mut at) = match interpolator {
                    Some(kind) => (kind, 1),
                    None => (Kind::Body, 0),
                };
                let expr = if kind == Kind::Embed {
                    // `embed name` or `embed template(arg, arg)`.
                    let name_start = at;
                    let path = parse_path(&toks, &mut at, file, pos)?;
                    if matches!(toks.get(at), Some((Tok::LParen, _))) && path.names.len() == 1 {
                        at += 1;
                        let mut args = Vec::new();
                        if !matches!(toks.get(at), Some((Tok::RParen, _))) {
                            loop {
                                args.push(parse_path(&toks, &mut at, file, pos)?);
                                match toks.get(at) {
                                    Some((Tok::Comma, _)) => at += 1,
                                    _ => break,
                                }
                            }
                        }
                        match toks.get(at) {
                            Some((Tok::RParen, _)) => at += 1,
                            other => {
                                return Err(TemplateError::at(
                                    "BadExpression",
                                    "expected `,` or `)` in the argument list",
                                    file,
                                    other.map(|(_, pos)| *pos).unwrap_or(pos),
                                ))
                            }
                        }
                        Expr::Call {
                            name: path.names[0].clone(),
                            pos: toks[name_start].1,
                            args,
                        }
                    } else {
                        Expr::Path(path)
                    }
                } else {
                    Expr::Path(parse_path(&toks, &mut at, file, pos)?)
                };
                expect_end(&toks, at, file)?;
                push(&mut root, &mut stack, Node::Interp { kind, expr, pos });
            }
            Piece::Stmt { body, pos } => {
                let toks = tokens(&body);
                let word = match toks.first() {
                    Some((Tok::Ident(word), _)) => word.clone(),
                    _ => String::new(),
                };
                let was_header = in_header;
                match word.as_str() {
                    "import" | "params" => {
                        if !in_header || !stack.is_empty() || (word == "params" && params.is_some())
                        {
                            return Err(TemplateError::at(
                                "HeaderPosition",
                                format!("`{word}` belongs in the header, before any content, and `params` appears once"),
                                file,
                                pos,
                            ));
                        }
                        if word == "import" {
                            let text = body.iter().map(|(c, _)| *c).collect::<String>();
                            let rest = text.trim().trim_start_matches("import").trim();
                            let inner = rest.get(1..rest.len().saturating_sub(1)).unwrap_or("");
                            let valid = rest.len() >= 2
                                && rest.starts_with('"')
                                && rest.ends_with('"')
                                && !inner.contains(['"', '\\', '\n', '\r'])
                                && (inner.starts_with("std:")
                                    || inner.starts_with("pkg:")
                                    || (inner.ends_with(".gu")
                                        && !inner.starts_with('/')
                                        && !inner
                                            .split('/')
                                            .any(|part| part == ".." || part == ".")));
                            if !valid {
                                return Err(TemplateError::at(
                                    "BadImport",
                                    "write `{% import \"relative/path.gu\" %}` (a path inside this directory or below, `pkg:` or `std:`)",
                                    file,
                                    pos,
                                ));
                            }
                            imports.push((inner.to_owned(), pos));
                        } else {
                            params = Some((parse_params(&body, file, pos)?, pos));
                        }
                        swallow_break = true;
                        continue;
                    }
                    _ => {}
                }
                let _ = was_header;
                in_header = false;
                swallow_break = false;
                match word.as_str() {
                    "for" => {
                        let mut at = 1;
                        let (var, var_pos) = match toks.get(at) {
                            Some((Tok::Ident(name), pos)) => (name.clone(), *pos),
                            _ => return Err(TemplateError::at("BadExpression", "write `{% for name in list %}`", file, pos)),
                        };
                        at += 1;
                        match toks.get(at) {
                            Some((Tok::Ident(word), _)) if word == "in" => at += 1,
                            _ => return Err(TemplateError::at("BadExpression", "write `{% for name in list %}`", file, pos)),
                        }
                        let list = parse_path(&toks, &mut at, file, pos)?;
                        expect_end(&toks, at, file)?;
                        stack.push(Frame::For { var, var_pos, list, pos, nodes: Vec::new() });
                    }
                    "if" => {
                        let mut at = 1;
                        let negate = matches!(toks.get(at), Some((Tok::Ident(word), _)) if word == "not")
                            && matches!(toks.get(at + 1), Some((Tok::Ident(_), _)));
                        if negate {
                            at += 1;
                        }
                        let cond = parse_path(&toks, &mut at, file, pos)?;
                        expect_end(&toks, at, file)?;
                        stack.push(Frame::If { negate, cond, pos, nodes: Vec::new(), then: None });
                    }
                    "else" => {
                        expect_end(&toks, 1, file)?;
                        match stack.last_mut() {
                            Some(Frame::If { nodes, then, .. }) if then.is_none() => {
                                *then = Some(std::mem::take(nodes));
                            }
                            _ => {
                                return Err(TemplateError::at(
                                    "UnexpectedElse",
                                    "`else` belongs to an `if` that has not had one yet",
                                    file,
                                    pos,
                                ))
                            }
                        }
                    }
                    "end" => {
                        expect_end(&toks, 1, file)?;
                        let Some(frame) = stack.pop() else {
                            return Err(TemplateError::at(
                                "UnbalancedEnd",
                                "`end` closes nothing: there is no open `for` or `if`",
                                file,
                                pos,
                            ));
                        };
                        let node = match frame {
                            Frame::For { var, var_pos, list, pos, nodes } => Node::For { var, var_pos, list, body: nodes, pos },
                            Frame::If { negate, cond, pos, nodes, then } => match then {
                                Some(then) => Node::If { negate, cond, then, otherwise: Some(nodes), pos },
                                None => Node::If { negate, cond, then: nodes, otherwise: None, pos },
                            },
                        };
                        push(&mut root, &mut stack, node);
                    }
                    _ => {
                        return Err(TemplateError::at(
                            "UnknownTag",
                            "block tags are `for`, `if`, `else`, `end`, and the header directives `import` and `params`",
                            file,
                            pos,
                        ))
                    }
                }
            }
        }
    }
    if let Some(frame) = stack.last() {
        return Err(TemplateError::at(
            "UnbalancedBlock",
            "this block is never closed with `{% end %}`",
            file,
            frame.pos(),
        ));
    }
    let (params, params_pos) = params.unwrap_or((Vec::new(), (1, 1)));
    Ok(Template {
        imports,
        params,
        params_pos,
        body: root,
    })
}

fn push(root: &mut Vec<Node>, stack: &mut [Frame], node: Node) {
    match stack.last_mut() {
        Some(frame) => frame.nodes().push(node),
        None => root.push(node),
    }
}

fn parse_params(body: &[(char, Pos)], file: &str, tag: Pos) -> Result<Vec<Param>, TemplateError> {
    // Skip the word `params`, then split at commas that are not inside brackets.
    let mut index = 0;
    while index < body.len() && body[index].0.is_whitespace() {
        index += 1;
    }
    index += "params".len();
    let mut segments: Vec<Vec<(char, Pos)>> = vec![Vec::new()];
    let mut depth = 0i32;
    for &(c, pos) in &body[index.min(body.len())..] {
        match c {
            '[' | '(' => depth += 1,
            ']' | ')' => depth -= 1,
            _ => {}
        }
        if c == ',' && depth == 0 {
            segments.push(Vec::new());
        } else {
            segments.last_mut().unwrap().push((c, pos));
        }
    }
    let segments_len = segments.len();
    let mut params = Vec::new();
    let mut seen = BTreeSet::new();
    for segment in segments {
        let trimmed = segment
            .iter()
            .copied()
            .skip_while(|(c, _)| c.is_whitespace())
            .collect::<Vec<_>>();
        if trimmed.is_empty() {
            if params.is_empty() && segments_len == 1 {
                continue;
            }
            return Err(TemplateError::at(
                "BadParams",
                "an empty parameter; write `name: Type`",
                file,
                tag,
            ));
        }
        let start = trimmed[0].1;
        let text = trimmed.iter().map(|(c, _)| *c).collect::<String>();
        let Some((name, ty)) = text.split_once(':') else {
            return Err(TemplateError::at(
                "BadParams",
                "write each parameter as `name: Type`",
                file,
                start,
            ));
        };
        let name = name.trim();
        let ty = ty.trim();
        if !is_identifier(name)
            || ty.is_empty()
            || ty.contains('\n')
            || !ty
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || "_[](), .->".contains(c))
        {
            return Err(TemplateError::at(
                "BadParams",
                "write each parameter as `name: Type`, a name and a Guion type",
                file,
                start,
            ));
        }
        if let Some(why) = reserved_name(name) {
            return Err(TemplateError::at(
                "ReservedName",
                format!("`{name}` is {why}; pick another parameter name"),
                file,
                start,
            ));
        }
        if !seen.insert(name.to_owned()) {
            return Err(TemplateError::at(
                "DuplicateVariable",
                format!("`{name}` is declared twice"),
                file,
                start,
            ));
        }
        params.push(Param {
            name: name.to_owned(),
            ty: ty.to_owned(),
        });
    }
    Ok(params)
}

